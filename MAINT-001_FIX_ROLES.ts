// NEW: src/domain/auth/roles.ts
// Supports the permission system

import { PERMISSIONS, type Permission } from "./permissions";

export const ROLES = {
  SUPER_ADMIN:  "super_admin",
  SCHOOL_ADMIN: "school_admin",
  PRINCIPAL:    "principal",
  TEACHER:      "teacher",
  ACCOUNTANT:   "accountant",
  STUDENT:      "student",
  PARENT:       "parent",
} as const;

export type RoleName = (typeof ROLES)[keyof typeof ROLES];

/** Least-privilege defaults. Unknown roles get NOTHING. */
export const DEFAULT_ROLE_PERMISSIONS: Record<RoleName, readonly Permission[]> = {
  [ROLES.SUPER_ADMIN]: [PERMISSIONS.WILDCARD],
  [ROLES.SCHOOL_ADMIN]: [
    PERMISSIONS.ADMIN_READ, PERMISSIONS.ADMIN_WRITE, PERMISSIONS.ADMIN_MANAGE,
    PERMISSIONS.STUDENTS_READ, PERMISSIONS.STUDENTS_WRITE, PERMISSIONS.STUDENTS_DELETE,
    PERMISSIONS.STAFF_READ, PERMISSIONS.STAFF_WRITE,
    PERMISSIONS.FINANCE_READ, PERMISSIONS.FINANCE_WRITE,
    PERMISSIONS.ACADEMICS_READ, PERMISSIONS.ACADEMICS_WRITE,
  ],
  [ROLES.PRINCIPAL]: [
    PERMISSIONS.STUDENTS_READ, PERMISSIONS.STUDENTS_WRITE,
    PERMISSIONS.STAFF_READ,
    PERMISSIONS.ACADEMICS_READ, PERMISSIONS.ACADEMICS_WRITE,
  ],
  [ROLES.TEACHER]: [
    PERMISSIONS.STUDENTS_READ,
    PERMISSIONS.ACADEMICS_READ, PERMISSIONS.ACADEMICS_WRITE,
  ],
  [ROLES.ACCOUNTANT]: [
    PERMISSIONS.FINANCE_READ, PERMISSIONS.FINANCE_WRITE,
    PERMISSIONS.STUDENTS_READ,
  ],
  [ROLES.STUDENT]: [PERMISSIONS.ACADEMICS_READ],
  [ROLES.PARENT]:  [PERMISSIONS.STUDENTS_READ, PERMISSIONS.FINANCE_READ],
};

export function isRoleName(v: unknown): v is RoleName {
  return typeof v === "string" && v in DEFAULT_ROLE_PERMISSIONS;
}